"""Summarise foundation-fields.csv: which module first defines each field, and which app family it belongs to.

Usage: python -I field_owners.py <catalogue/odoo-20.0 dir>
Writes foundation-fields-by-owner.md next to the CSV and prints a summary.
"""
import csv, json, os, sys
from collections import defaultdict, OrderedDict

d = sys.argv[1]
mods = json.load(open(os.path.join(d, 'modules.json'), encoding='utf-8'))
rows = list(csv.DictReader(open(os.path.join(d, 'foundation-fields.csv'), encoding='utf-8')))

TECH = {'id', 'display_name', 'create_uid', 'create_date', 'write_uid', 'write_date', '__last_update'}
MIXIN_PREFIX = ('message_', 'activity_', 'website_message', 'rating_', 'access_', 'has_message')
FOUNDATION_KINDS = {'foundation', 'foundation app'}


def family(module):
    v = mods.get(module)
    if not v:
        return module, 'unknown'
    if v['kind'] in FOUNDATION_KINDS:
        return 'foundation', v['kind']
    apps = v.get('apps') or []
    label = ' + '.join(mods[a]['name'] if a in mods else a for a in apps) or module
    return label, v['kind']


by_model = OrderedDict()
for r in rows:
    if r['name'] in TECH:
        continue
    owner = (r['modules'] or '').split(' ')[0]
    fam, kind = family(owner)
    tech = r['name'].startswith(MIXIN_PREFIX)
    r['owner'], r['family'], r['kind'], r['mixin'] = owner, fam, kind, tech
    by_model.setdefault(r['model'], []).append(r)

out = ['# Foundation models: who defines each field (generated)', '',
       'Source: the local Odoo 20 Community (`external/odoo20-local`, 267 modules installed), `ir_model_fields` and `ir_model_data`. '
       'Owner = the first module that declares the field. "Foundation" = modules that belong to no app (catalogue kind foundation). '
       'Mixin fields (messages, activities, ratings, portal access) are counted apart: HAP has its own discussion and log. '
       'Generated by `field_owners.py`; do not edit.', '']
summary = []
for model, fs in by_model.items():
    biz = [f for f in fs if not f['mixin']]
    found = [f for f in biz if f['family'] == 'foundation']
    other = defaultdict(list)
    for f in biz:
        if f['family'] != 'foundation':
            other[f['family']].append(f)
    stored_found = [f for f in found if f['store'] == 't']
    summary.append((model, len(fs), len(biz), len(found), len(stored_found), {k: len(v) for k, v in other.items()}))
    out += [f'## `{model}`', '',
            f'{len(biz)} business fields ({len(fs) - len(biz)} mixin): **{len(found)} from foundation modules** '
            f'({len(stored_found)} stored), the rest added by other modules.', '']
    out.append('| Defined by | Fields |')
    out.append('|---|---|')
    out.append('| foundation (' + ', '.join(sorted({f["owner"] for f in found})) + ') | ' +
               ', '.join(f"`{f['name']}`" + ('' if f['store'] == 't' else '*') for f in found) + ' |')
    for fam in sorted(other, key=lambda k: -len(other[k])):
        out.append(f'| {fam} ({", ".join(sorted({f["owner"] for f in other[fam]}))}) | ' +
                   ', '.join(f"`{f['name']}`" + ('' if f['store'] == 't' else '*') for f in other[fam]) + ' |')
    out.append('')
out.append('`*` = computed and not stored in Odoo.')
open(os.path.join(d, 'foundation-fields-by-owner.md'), 'w', encoding='utf-8').write('\n'.join(out) + '\n')
for s in summary:
    print(f"{s[0]:34} all {s[1]:3} business {s[2]:3} foundation {s[3]:3} (stored {s[4]:3}) | others: " +
          ', '.join(f'{k} {v}' for k, v in sorted(s[5].items(), key=lambda kv: -kv[1])[:6]))
